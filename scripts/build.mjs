import { build, context } from 'esbuild';
import { spawn, spawnSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const options = {
  entryPoints: ['src/webview/main.ts'],
  outfile: 'media/viewer.js',
  bundle: true,
  platform: 'browser',
  format: 'iife',
  target: 'es2022',
  banner: { js: '// Generated by npm run compile from src/webview/main.ts. Do not edit directly.' },
};
// The MCP server that Claude Code, Codex, and other agents start: one file,
// copied to ~/.logline/mcp.js, with the tool declarations from package.json.
const manifest = JSON.parse(readFileSync('package.json', 'utf8'));
const mcpOptions = {
  entryPoints: ['src/mcp/main.ts'],
  outfile: 'out/mcp.js',
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node18',
  define: {
    LOGLINE_TOOLS: JSON.stringify(manifest.contributes.languageModelTools),
    LOGLINE_VERSION: JSON.stringify(manifest.version),
  },
  banner: { js: '// Logline MCP server. Generated by npm run compile from src/mcp/main.ts.' },
};
// The Postgres client, loaded only when a Postgres connection is used. The
// package ships no node_modules besides re2-wasm, so pg is bundled into one
// file with the license of every package it contains.
const vendorOptions = {
  stdin: { contents: "module.exports = require('pg');", resolveDir: '.', sourcefile: 'pg.js' },
  outfile: 'out/vendor/pg.js',
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node18',
  // Optional native bindings and the Cloudflare socket shim; pg falls back without them.
  external: ['pg-native', 'cloudflare:sockets'],
  metafile: true,
  banner: { js: '// pg (node-postgres), bundled by npm run compile. Licenses: pg.LICENSES.txt.' },
};
async function buildVendor() {
  const { metafile } = await build(vendorOptions);
  const packages = new Set();
  for (const input of Object.keys(metafile.inputs)) {
    const match = input.match(/^(?:.*\/)?node_modules\/((?:@[^/]+\/)?[^/]+)\//);
    if (match) packages.add(join('node_modules', match[1]));
  }
  const notices = [...packages].sort().map((folder) => {
    const manifest = JSON.parse(readFileSync(join(folder, 'package.json'), 'utf8'));
    const file = readdirSync(folder).find((name) => /^(?:licen[cs]e|copying)(?:\.|$)/i.test(name));
    const text = file ? readFileSync(join(folder, file), 'utf8').trim() : `License: ${manifest.license}`;
    return `${manifest.name} ${manifest.version}\n\n${text}\n`;
  });
  writeFileSync(join(dirname(vendorOptions.outfile), 'pg.LICENSES.txt'), notices.join('\n' + '-'.repeat(72) + '\n\n'));
}
const tsc = 'node_modules/typescript/bin/tsc';
if (process.argv.includes('--watch')) {
  const browser = await context(options);
  await browser.watch();
  const mcp = await context(mcpOptions);
  await mcp.watch();
  if (!existsSync(vendorOptions.outfile)) await buildVendor();
  const host = spawn(process.execPath, [tsc, '--watch', '--preserveWatchOutput'], { stdio: 'inherit' });
  const types = spawn(process.execPath, [tsc, '-p', 'tsconfig.webview.json', '--watch', '--preserveWatchOutput'], {
    stdio: 'inherit',
  });
  const stop = async () => {
    host.kill();
    types.kill();
    await browser.dispose();
    await mcp.dispose();
  };
  process.once('SIGINT', stop);
  process.once('SIGTERM', stop);
} else {
  // Removed or moved modules must not linger in the extension package.
  rmSync('out', { recursive: true, force: true });
  const result = spawnSync(process.execPath, [tsc], { stdio: 'inherit' });
  if (result.status !== 0) process.exit(result.status ?? 1);
  const browserTypes = spawnSync(process.execPath, [tsc, '-p', 'tsconfig.webview.json'], { stdio: 'inherit' });
  if (browserTypes.status !== 0) process.exit(browserTypes.status ?? 1);
  await build(options);
  await build(mcpOptions);
  await buildVendor();
}
